// ============================================================================
//  exportPdf.ts — dependency-free PDF (.pdf) generation + print
// ============================================================================
//  Builds a single-page PDF by hand (raw PDF 1.4 objects + xref table) and
//  triggers a browser download. No npm install required — works offline.
//  Also provides a print() helper that opens a clean printable report window
//  (the browser's print dialog → "Save as PDF" prints to PDF).
//
//  Used by the Completed Tests screen for the report Download / Print actions.
// ============================================================================

export interface ReportField { label: string; value: string; }

/* Escape a string for a PDF text literal and drop any non-ASCII bytes so the
   hand-computed xref byte offsets stay correct. */
const pdfEsc = (s: string): string =>
  String(s ?? '')
    .replace(/[^\x20-\x7E]/g, ' ')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');

/**
 * Build a one-page A4 PDF report (title + section label + key/value fields).
 * Returns a Blob ready to download.
 */
export function buildReportPdf(
  title: string,
  subtitle: string,
  fields: ReportField[],
  footer = 'Generated by Vexoo — Lab Technician Portal',
): Blob {
  const left = 56;
  let y = 792;
  const ops: string[] = ['BT'];

  // Title (Helvetica-Bold 20)
  ops.push('/F2 20 Tf', `1 0 0 1 ${left} ${y} Tm`, `(${pdfEsc(title)}) Tj`);
  y -= 22;
  // Subtitle (Helvetica 11, grey-ish — PDF base fonts have no colour here, plain)
  ops.push('/F1 11 Tf', `1 0 0 1 ${left} ${y} Tm`, `(${pdfEsc(subtitle)}) Tj`);
  y -= 26;

  // Fields: bold label then value on the same line.
  for (const f of fields) {
    ops.push('/F2 11 Tf', `1 0 0 1 ${left} ${y} Tm`, `(${pdfEsc(f.label + ':')}) Tj`);
    ops.push('/F1 11 Tf', `1 0 0 1 ${left + 150} ${y} Tm`, `(${pdfEsc(f.value)}) Tj`);
    y -= 22;
  }

  y -= 14;
  ops.push('/F1 9 Tf', `1 0 0 1 ${left} ${y} Tm`, `(${pdfEsc(footer)}) Tj`);
  ops.push('ET');
  const stream = ops.join('\n');

  const objects: string[] = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] '
      + '/Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 4 0 R >>',
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
  ];

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((body, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefPos = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.forEach(off => { pdf += `${off.toString().padStart(10, '0')} 00000 n \n`; });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefPos}\n%%EOF`;

  return new Blob([pdf], { type: 'application/pdf' });
}

/** Trigger a browser download of a PDF blob. */
export function downloadPdf(filename: string, blob: Blob): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename.endsWith('.pdf') ? filename : `${filename}.pdf`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}

const htmlEsc = (s: string): string =>
  String(s ?? '')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/**
 * Open a clean printable report in a new window and invoke the print dialog.
 * Choosing "Save as PDF" in the dialog prints the report to PDF.
 */
export function printReport(title: string, subtitle: string, fields: ReportField[]): void {
  const rows = fields
    .map(f => `<tr><th>${htmlEsc(f.label)}</th><td>${htmlEsc(f.value)}</td></tr>`)
    .join('');
  const html =
    `<!doctype html><html><head><meta charset="utf-8"><title>${htmlEsc(title)}</title>` +
    `<style>` +
    `*{box-sizing:border-box;}` +
    `body{font-family:'Inter Tight',Arial,Helvetica,sans-serif;color:#0E1413;margin:40px;}` +
    `h1{font-family:Georgia,'Times New Roman',serif;font-size:26px;margin:0 0 4px;}` +
    `.sub{color:#5b6360;font-size:13px;margin:0 0 24px;}` +
    `table{border-collapse:collapse;width:100%;max-width:560px;}` +
    `th,td{text-align:left;padding:9px 12px;border-bottom:1px solid #e7e7e2;font-size:13.5px;vertical-align:top;}` +
    `th{width:170px;color:#5b6360;font-weight:600;text-transform:uppercase;letter-spacing:.05em;font-size:11px;}` +
    `.foot{margin-top:28px;color:#9aa09d;font-size:11px;}` +
    `</style></head><body>` +
    `<h1>${htmlEsc(title)}</h1><p class="sub">${htmlEsc(subtitle)}</p>` +
    `<table>${rows}</table>` +
    `<p class="foot">Generated by Vexoo — Lab Technician Portal</p>` +
    `</body></html>`;

  const w = window.open('', '_blank', 'width=820,height=900');
  if (!w) return;
  w.document.open();
  w.document.write(html);
  w.document.close();
  // Give the new window a tick to lay out before printing.
  setTimeout(() => { w.focus(); w.print(); }, 350);
}
